/**
 * Intelligent User Country Detector
 * Uses browser timezone and language to auto-detect the user's origin country.
 */
export function detectUserOriginCountry(): OriginCountryInfo {
  try {
    const tz = Intl.DateTimeFormat().resolvedOptions().timeZone || '';
    const userLangs = navigator.languages || [navigator.language || ''];

    // 1. Check by Timezone
    for (const c of ORIGIN_COUNTRIES) {
      if (c.matchTimezones?.some(t => tz.includes(t) || tz.startsWith(t))) {
        return c;
      }
    }

    // 2. Check by Language tag
    for (const lang of userLangs) {
      for (const c of ORIGIN_COUNTRIES) {
        if (c.matchLanguages?.some(ml => lang.toLowerCase().startsWith(ml.toLowerCase()))) {
          return c;
        }
      }
    }
  } catch (e) {
    console.error('Error detecting user country', e);
  }

  // Default fallback to Spain (or US based on simple lang)
  const isSpanish = navigator.language?.startsWith('es');
  return isSpanish ? ORIGIN_COUNTRIES[0] : ORIGIN_COUNTRIES[1];
}
